    ADD CONSTRAINT fk_projects_active_version
    FOREIGN KEY (active_version_id)
    REFERENCES menu_versions(version_id);

CREATE TABLE sections (
    section_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_id NUMBER(19) NOT NULL,
    name VARCHAR2(255) NOT NULL,
    display_order NUMBER(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_sections_version FOREIGN KEY (version_id) REFERENCES menu_versions(version_id)
);

CREATE TABLE items (
    item_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(255) NOT NULL,
    description CLOB,
    category VARCHAR2(255),
    price NUMBER(12, 2),
    dph NUMBER(5, 2),
    allergens VARCHAR2(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE TABLE menu_items (
    menu_item_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    section_id NUMBER(19) NOT NULL,
    item_id NUMBER(19) NOT NULL,
    servings_per_person NUMBER(8, 2),
    price_at_version NUMBER(12, 2),
    display_order NUMBER(10) NOT NULL,
    notes CLOB,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_menu_items_section FOREIGN KEY (section_id) REFERENCES sections(section_id),
    CONSTRAINT fk_menu_items_item FOREIGN KEY (item_id) REFERENCES items(item_id)
);

